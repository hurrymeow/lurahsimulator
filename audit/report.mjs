// Turns audit/out/*.json into audit/report.md: one row per screen and rule that failed, then a per-project summary.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const files = readdirSync('audit/out').filter((f) => f.endsWith('.json')).sort();
const fails = new Map();
let screens = 0;
const projects = new Set();
for (const f of files) {
  const project = f.replace(/-(rt3|rw|kel|kec)\.json$/, '');
  projects.add(project);
  for (const r of JSON.parse(readFileSync(`audit/out/${f}`, 'utf8'))) {
    screens++;
    for (const [rule, list] of [['1/4/5 legibility', r.legibility], ['13/14 density', r.density], ['16 label words', r.labels], ['18 centring', r.centring]]) {
      for (const item of list) {
        const key = `${rule} | ${r.screen} | ${item}`;
        const e = fails.get(key) ?? { rule, screen: r.screen, item, where: new Set() };
        e.where.add(`${project}/${r.seed}`);
        fails.set(key, e);
      }
    }
  }
}
const all = [...fails.values()];
const known = all.filter((r) => r.item.startsWith('(allowlisted)'));
const rows = all.filter((r) => !r.item.startsWith('(allowlisted)')).sort((a, b) => a.rule.localeCompare(b.rule) || a.screen.localeCompare(b.screen));
const out = [
  '# UI audit',
  '',
  `Generated by \`npm run audit:ui\` (audit/ui-audit.spec.ts). ${projects.size} projects (width, language, theme) x 4 stage saves; ${screens} screens scanned.`,
  '',
  rows.length ? `**${rows.length} distinct fails.**` : '**Every screen passes, apart from the allowlisted screens below.**',
  '',
  '| Rule | Screen | What | Where (count) |',
  '| --- | --- | --- | --- |',
  ...rows.map((r) => `| ${r.rule} | ${r.screen} | ${r.item.replace(/\|/g, '/')} | ${[...r.where].slice(0, 3).join(', ')}${r.where.size > 3 ? ` +${r.where.size - 3}` : ''} (${r.where.size}) |`),
  '',
  `Known fails on the e2e allowlist (\`DENSITY_ALLOW\` in tests/e2e/density.ts), within their caps: ${[...new Set(known.map((r) => `${r.screen} (${r.item.replace('(allowlisted) ', '')})`))].join('; ') || 'none'}.`,
];
writeFileSync('audit/report.md', out.join('\n') + '\n');
console.log(`${screens} screens, ${rows.length} distinct fails`);
